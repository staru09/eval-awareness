#!/usr/bin/env python3
"""Experiment A: capture activations over the PROMPT ONLY, before generation.

Companion to run_inference.py's activation capture, which pools hidden
states over `prompt + the model's own generated answer` (run_inference.py's
second forward pass over `gen_out`). That readout answers "is the
eval/deploy distinction present somewhere in the episode?" -- but its last
token is the last token the *model wrote*, which for benchmark transcripts
is often literally the end of a LaTeX-boxed multiple-choice answer letter.
A probe read there is partly reading the model's own output format back
to itself.

This script reads at the last token of the prompt instead, before a single
answer token exists -- the readout the source paper and
../../evaluation-awareness/cls_corr_mi/score_prompts.py use. That supports
the stronger claim: the model represents "this is an evaluation" *before*
it decides how to answer, which is the ordering that matters for whether
eval-awareness could influence behaviour at all.

No generation happens here: one forward pass per transcript over a prompt
that was already built and stored by run_inference.py. Prompts come from
`reasoning_traces.json`'s `templated_prompt` field, which is the exact
string that was fed to generate() -- reusing it (rather than re-applying
the chat template) guarantees the token sequence is byte-identical to the
one the prompt+answer run saw, so the two readouts differ only in *where*
they are read, never in *what* was read.

Pooling is delegated to run_inference.pool_hidden_states, unchanged, so
both readouts share one definition of "last token" and "mean token" and
one embedding-layer-dropping convention (activation index i = decoder
layer i+1, matching score_activations.py).

Output schema is a superset of run_inference.py's activations/*.npz (it
adds `n_prompt_tokens` and a `readout` marker), so score_activations.py
--activations-dir works against it with no changes -- it reads only
`last_token`/`mean_token` and ignores everything else:

    last_token  float32 [n_layers, d_model]
    mean_token  float32 [n_layers, d_model]
    label, prompt_id, source, n_layers, d_model, n_prompt_tokens
    readout     "prompt_only"   (marker; the prompt+answer files have none)

Usage:
    python capture_prompt_activations.py \
      --model-path Qwen/Qwen3-8B \
      --reasoning-traces ../output/local/qwen3-8b/reasoning_traces.json \
      --out-dir ../output/local/qwen3-8b/activations_prompt
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "inference"))
from model_utils import ModelSpec, QWEN3_8B, apply_chat_template, load_hf_model  # noqa: E402
from run_inference import pool_hidden_states  # noqa: E402


def load_rows(traces_path: Path | None, dataset_path: Path | None, spec, tok,
              model_path: str) -> list[dict]:
    """Return [{id, prompt_id, source, label, prompt, n_prompt_tokens}] per transcript.

    Prefers reasoning_traces.json's stored `templated_prompt` (the exact
    string generate() saw). Falls back to re-templating dataset.json for
    models that have no local generation run -- usable, but the token
    sequence is then only reproducible, not provably identical.
    """
    if traces_path is not None:
        traces = json.loads(traces_path.read_text(encoding="utf-8"))
        missing = [t["id"] for t in traces if not t.get("templated_prompt")]
        if missing:
            raise SystemExit(
                f"{len(missing)} transcript(s) in {traces_path} have no "
                f"'templated_prompt' (first: {missing[0]!r}). Re-run "
                "run_inference.py, or pass --dataset to re-template instead."
            )
        # Guard against the one failure mode that produces plausible but
        # meaningless numbers instead of an error: templating strings from
        # model A through model B's tokenizer. d_model comes from the
        # *loaded* model, so every downstream shape still lines up and the
        # run completes silently. run_inference.py:200 records which model
        # actually produced these prompts -- use it.
        trace_model = next((t.get("model") for t in traces if t.get("model")), None)
        if trace_model and trace_model != model_path:
            raise SystemExit(
                f"{traces_path} was generated by {trace_model!r}, but --model-path "
                f"is {model_path!r}. Tokenizing one model's templated prompts with "
                "another model's tokenizer produces meaningless activations without "
                "raising. Pass the matching --model-path."
            )
        return [
            {
                "id": t["id"],
                "prompt_id": int(t["prompt_id"]),
                "source": t["source"],
                "label": int(t["ground_truth_label"]),
                "prompt": t["templated_prompt"],
                # written by run_inference.py:192 during the generation run
                "n_prompt_tokens": t.get("n_prompt_tokens"),
            }
            for t in traces
        ]

    print(
        "WARNING: --dataset fallback re-templates prompts from scratch with "
        f"enable_thinking={spec.enable_thinking}. If the prompt+answer run used a "
        "different setting, the two readouts will differ in *what* was read, not "
        "just where -- which is the confound this experiment exists to avoid. "
        "Prefer --reasoning-traces whenever a generation run exists."
    )
    dataset = json.loads(dataset_path.read_text(encoding="utf-8"))
    return [
        {
            "id": r["id"],
            "prompt_id": int(r["prompt_id"]),
            "source": r["source"],
            "label": int(r["label"]),
            "prompt": apply_chat_template(tok, r["text"], spec),
            "n_prompt_tokens": None,  # nothing recorded to cross-check against
        }
        for r in dataset
    ]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model-path", default=QWEN3_8B.hf_id)
    ap.add_argument("--reasoning-traces", type=Path, default=None,
                    help="preferred: reuse the exact templated_prompt strings from a generation run")
    ap.add_argument("--dataset", type=Path, default=None,
                    help="fallback when no generation run exists: re-template data/dataset.json")
    ap.add_argument("--out-dir", required=True, type=Path)
    ap.add_argument("--dtype", default="bfloat16", choices=["float16", "bfloat16", "float32"])
    ap.add_argument("--enable-thinking", dest="enable_thinking", action="store_true", default=True,
                    help="only used by the --dataset fallback path; ignored when reusing templated_prompt")
    ap.add_argument("--no-thinking", dest="enable_thinking", action="store_false")
    ap.add_argument("--limit", type=int, default=None,
                    help="capture only the first N transcripts. Smoke test only: "
                         "score_activations.py iterates the whole dataset and exits on the "
                         "first missing .npz, so a limited dir cannot be scored.")
    args = ap.parse_args()

    if (args.reasoning_traces is None) == (args.dataset is None):
        raise SystemExit("Pass exactly one of --reasoning-traces (preferred) or --dataset.")
    if args.out_dir.name == "activations":
        raise SystemExit(
            f"Refusing to write to {args.out_dir}: 'activations/' is run_inference.py's "
            "prompt+answer directory, and these prompt-only files are indistinguishable "
            "from it by shape. Use e.g. 'activations_prompt/'."
        )

    import torch

    spec = ModelSpec(hf_id=args.model_path, chat_template=True, enable_thinking=args.enable_thinking)
    print(f"Loading {args.model_path} (dtype={args.dtype}) ...")
    model, tok = load_hf_model(args.model_path, dtype=args.dtype)

    rows = load_rows(args.reasoning_traces, args.dataset, spec, tok, args.model_path)
    if args.limit:
        rows = rows[: args.limit]
    print(f"{len(rows)} transcripts; prompts from "
          f"{'templated_prompt' if args.reasoning_traces else 'dataset.json (re-templated)'}")

    text_config = model.config.get_text_config()
    n_layers = text_config.num_hidden_layers
    d_model = text_config.hidden_size

    args.out_dir.mkdir(parents=True, exist_ok=True)

    for row in rows:
        t0 = time.time()
        # add_special_tokens=False matches run_inference.py: the chat
        # template already emits whatever BOS/role tokens the model needs,
        # and adding another would shift every position by one.
        inputs = tok(row["prompt"], return_tensors="pt", add_special_tokens=False).to(model.device)
        n_tok = int(inputs["input_ids"].shape[1])
        # The docstring's "byte-identical token sequence" claim, enforced
        # rather than asserted: any tokenizer drift (different HF revision,
        # updated trust_remote_code tokenizer, added special tokens) shifts
        # the last-token position and we would silently read the wrong
        # residual-stream slot.
        if row.get("n_prompt_tokens") is not None and n_tok != row["n_prompt_tokens"]:
            raise SystemExit(
                f"{row['id']}: prompt retokenized to {n_tok} tokens, but the generation "
                f"run recorded {row['n_prompt_tokens']}. The tokenizer has drifted since "
                "that run -- the last-token readout would not be comparable."
            )
        with torch.no_grad():
            out = model(**inputs, output_hidden_states=True)
        last_h, mean_h = pool_hidden_states(out.hidden_states, inputs["attention_mask"])

        np.savez(
            args.out_dir / f"{row['id']}.npz",
            last_token=last_h.astype(np.float32),   # [n_layers, d_model]
            mean_token=mean_h.astype(np.float32),   # [n_layers, d_model]
            label=row["label"],
            prompt_id=row["prompt_id"],
            source=row["source"],
            n_layers=n_layers,
            d_model=d_model,
            n_prompt_tokens=n_tok,
            readout="prompt_only",
        )
        print(f"[{row['id']}] {int(inputs['input_ids'].shape[1])} prompt tokens "
              f"-> {last_h.shape} in {time.time() - t0:.2f}s")

    print(f"Wrote {len(rows)} prompt-only activation files to {args.out_dir}/")


if __name__ == "__main__":
    main()
