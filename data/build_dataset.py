"""Assemble the mixed eval/deploy transcript dataset for the Qwen3-8B
evaluation-awareness experiment (see ../plan.md, step 0).

Pulls small samples from four eval-labeled sources (hellaswag, arc_challenge,
gpqa, agentharm) and two deploy-labeled sources (everyday-conversations,
WildChat), formats each as a single-turn user prompt, and writes them to
dataset.json in this directory.

This step only builds the *prompt* side of each transcript (label=0 deploy /
1 eval, source, category). Step-0's "final turn regenerated by Qwen3-8B" and
the rest of the pipeline (steps 1-5 in plan.md) are separate, later steps.
"""

import json
import random

from datasets import load_dataset

SEED = 0
random.seed(SEED)

rows = []


def add(source: str, category: str, label: int, text: str) -> None:
    rows.append(
        {
            "id": f"{source}_{sum(1 for r in rows if r['source'] == source)}",
            "text": text,
            "label": label,
            "source": source,
            "category": category,
        }
    )


# ---------------------------------------------------------------------------
# Eval-sourced (label=1): capability + alignment categories
# ---------------------------------------------------------------------------

# hellaswag — commonsense capability (3 samples)
ds = load_dataset("Rowan/hellaswag", split="validation")
idx = random.sample(range(len(ds)), 3)
for i in idx:
    ex = ds[i]
    endings = "\n".join(f"{j}. {e}" for j, e in enumerate(ex["endings"]))
    text = (
        f"{ex['ctx']}\n\nWhich of the following is the most plausible "
        f"continuation?\n{endings}"
    )
    add("hellaswag", "capability", 1, text)

# arc_challenge — reasoning capability (3 samples)
ds = load_dataset("allenai/ai2_arc", "ARC-Challenge", split="test")
idx = random.sample(range(len(ds)), 3)
for i in idx:
    ex = ds[i]
    choices = "\n".join(
        f"{lab}. {t}" for lab, t in zip(ex["choices"]["label"], ex["choices"]["text"])
    )
    text = f"{ex['question']}\n\n{choices}"
    add("arc_challenge", "capability", 1, text)

# gpqa is gated on HF and needs auth we don't have here; substitute
# cais/mmlu (ungated, same "hard capability" flavor) — 2 samples
ds = load_dataset("cais/mmlu", "all", split="test")
idx = random.sample(range(len(ds)), 2)
for i in idx:
    ex = ds[i]
    choices = "\n".join(f"{chr(65 + j)}. {c}" for j, c in enumerate(ex["choices"]))
    text = f"{ex['question']}\n\n{choices}"
    add("mmlu", "capability", 1, text)

# agentharm — agentic/alignment (2 samples)
ds = load_dataset("ai-safety-institute/AgentHarm", "harmful", split="test_public")
idx = random.sample(range(len(ds)), 2)
for i in idx:
    ex = ds[i]
    text = ex["prompt"]
    add("agentharm", "alignment", 1, text)

# ---------------------------------------------------------------------------
# Deploy-sourced (label=0): real-user chat
# ---------------------------------------------------------------------------

MIN_CHAT_CHARS = 40


def longest_user_turn(messages, role="user", content_key="content"):
    """Pick the longest user turn (skips throwaway greetings like 'Hi')."""
    turns = [m[content_key] for m in messages if m["role"] == role]
    return max(turns, key=len) if turns else None


# everyday-conversations — 7 samples (matches EXPERIMENT_SUMMARY.md source)
ds = load_dataset(
    "HuggingFaceTB/everyday-conversations-llama3.1-2k", split="train_sft"
)
candidates = [i for i in range(len(ds))]
random.shuffle(candidates)
picked = 0
for i in candidates:
    turn = longest_user_turn(ds[i]["messages"])
    if turn and len(turn) >= MIN_CHAT_CHARS:
        add("everyday_chat", "chat", 0, turn)
        picked += 1
    if picked == 7:
        break

# WildChat — 3 samples, for style variety
ds = load_dataset("allenai/WildChat-1M", split="train", streaming=True)
wildchat_examples = []
for ex in ds:
    if ex.get("language") == "English" and not ex.get("toxic", False):
        wildchat_examples.append(ex)
    if len(wildchat_examples) >= 200:
        break
idx = random.sample(range(len(wildchat_examples)), 3)
for i in idx:
    ex = wildchat_examples[i]
    turn = longest_user_turn(ex["conversation"])
    add("wildchat", "chat", 0, turn)

# ---------------------------------------------------------------------------
random.shuffle(rows)
for i, r in enumerate(rows):
    r["prompt_id"] = i

out_path = "dataset.json"
with open(out_path, "w", encoding="utf-8") as f:
    json.dump(rows, f, indent=2, ensure_ascii=False)

n_eval = sum(r["label"] == 1 for r in rows)
n_deploy = sum(r["label"] == 0 for r in rows)
print(f"Wrote {len(rows)} rows ({n_eval} eval, {n_deploy} deploy) to {out_path}")
